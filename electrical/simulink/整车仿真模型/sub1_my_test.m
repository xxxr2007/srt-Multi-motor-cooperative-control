%% ******************************输入车辆参数
% m是车辆总重量 (千克)
% Iz是车辆惯性的偏航力矩 (mNs^2)。
% lf是从重心到前轮胎 (m) 的纵向距离。
% lr是从重心到后轮胎 (m) 的纵向距离。
% Cf是前轮胎的转弯刚度 (N/rad)。
% Cr是后轮胎的转弯刚度 (N/rad)。
m = 2124+142;
Iz = 1523;
lf = 1.0;
lr = 1.4;
Cf = 83000;
Cr = 63000;
Vx = 80/3.6;% 速度 m/s.
%% ******************************二自由度模型状态方程.
% 状态变量: 横向速度和偏航角速率
% 输入变量: 前转向角度，速度
% 输出变量: 与状态变量相同
A = [-(2*Cf+2*Cr)/m/Vx, 0, -Vx-(2*Cf*lf-2*Cr*lr)/m/Vx, 0;
    0, 0, 1, 0;
    -(2*Cf*lf-2*Cr*lr)/Iz/Vx, 0, -(2*Cf*lf^2+2*Cr*lr^2)/Iz/Vx, 0;
    1, Vx, 0, 0];
B = [2*Cf/m 0 2*Cf*lf/Iz 0]';
C = [0 0 0 1; 0 1 0 0];
vehicle = ss(A,B,C,0);
%% 参考路径
T = 12;         % 仿真时间
Tstep=0.01;   %最好0.01  次好0.05
Ts = Tstep;
time = 0:Tstep:T; % 
%% ************************************设计MPC
mpc1 = mpc(vehicle,Ts);
display(mpc1)
mpc1.PredictionHorizon=15;%预测步数
mpc1.ControlHorizon=2;    %控制步数
%% 
k=3;%调节参数
mpc1.MV.RateMin = -0.26*k;  % %为了防止转向过于剧烈带来不舒适，限制转向速度
mpc1.MV.RateMax = 0.26*k;% %为了防止转向过于剧烈带来不舒适，限制转向速度

MPCobj.MV.Min = -0.1*pi;
MPCobj.MV.Max = 0.1*pi;
%% 要确保位置和偏航角的跟踪性能，将两个输出调整权重设置为非零。
mpc1.Weights.OV = [1 0]; 
%% 查看控制器
% review(mpc1);
%% *********************ADRC控制器**********
% TD参数
r_TD=10;   %跟踪速度因子  r_TD会影响跟踪精度和过渡过程时间,r_TD越大过渡时间越短，越大跟踪频带越高，但是容易引起超调；
h=0.001; %积分步长与采样时间相等即可
T=0.001;
% Ctrol参数
aa=[0.75,1.25];
bet1=[20 2.5];  %敏感，PD参数
% ESO参数
d=0.1;
bet=[100,65,80];
b=1; %关键







